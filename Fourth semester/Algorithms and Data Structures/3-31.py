def solve(n, matrix_A, sequence):
    """Решение задачи 31: моделирование химических реакций в пробирке."""
    stack = []

    for substance in sequence:
        # Помещаем новое вещество в пробирку (на вершину стека)
        stack.append(substance)

        # Пока в пробирке хотя бы 2 вещества и два верхних реагируют
        while len(stack) >= 2:
            top = stack[-1]
            below = stack[-2]
            product = matrix_A[top - 1][below - 1]  # -1 для перехода к 0-based индексам

            if product != 0:
                # Реакция произошла: удаляем два верхних вещества
                stack.pop()
                stack.pop()
                # Помещаем продукт реакции на вершину
                stack.append(product)
            else:
                # Реакции нет — выходим из цикла проверки
                break

    return stack


