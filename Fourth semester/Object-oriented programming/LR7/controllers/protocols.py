from typing import Protocol, Optional, List, runtime_checkable
from uuid import UUID
from models import User, Order, Courier, MenuItem

@runtime_checkable
class UserRepositoryProtocol(Protocol):
    def get_by_email(self, email: str) -> Optional[User]: ...
    def save(self, user: User) -> None: ...

@runtime_checkable
class OrderRepositoryProtocol(Protocol):
    def get_by_id(self, order_id: UUID) -> Optional[Order]: ...
    def save(self, order: Order) -> None: ...

@runtime_checkable
class CourierRepositoryProtocol(Protocol):
    def get_free(self) -> Optional[Courier]: ...
    def save(self, courier: Courier) -> None: ...

@runtime_checkable
class MenuItemRepositoryProtocol(Protocol):
    def get_all_available(self) -> List[MenuItem]: ...
    def save(self, item: MenuItem) -> None: ...